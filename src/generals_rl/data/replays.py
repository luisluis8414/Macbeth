"""FFA replays: read .gior files, convert them to compact game records, replay them through the simulator.

Pipeline
    scripts/download_replays.py   generals.io API -> data/raw/<set>/<id>.gior
    scripts/prepare_replays.py    .gior -> data/processed/<set>.npz   (iter_gior + replay_prep.prepare + to_record)
    bc.py                         load_game -> simulate on the GPU -> observations for any player and tick

On disk we keep only the game record (padded grid, the players' moves, AFK events, a few KB per game).
Observations are regenerated by replaying the game through the simulator, which is cheap in JAX.
"""
import json
from pathlib import Path

import jax
import jax.numpy as jnp
import numpy as np

from generals.core import game

from . import gior, replay_prep

PAD = replay_prep.PAD   # boards padded to 36 x 36 with mountains
NP = replay_prep.NP     # games padded to 8 players (absent players start eliminated)
PASS = replay_prep.PASS


# ---------------------------------------------------------------- reading

def iter_gior(path: str):
    """Yield (file name, replay row) for every .gior in a directory. Rows are in the format replay_prep expects
    plus `stars`; unreadable files are reported and skipped."""
    for f in sorted(Path(path).glob("*.gior")):
        try:
            r = gior.deserialize(f.read_bytes())
        except Exception as e:  # noqa: BLE001  (one corrupt download should not stop a long conversion)
            print(f"skipping {f.name}: {e}")
            continue
        r["moves"] = [[int(m[0]), int(m[1]), int(m[2]), int(bool(m[3])), int(m[4])] for m in r["moves"]]
        r["stars"] = [int(s or 0) for s in r.get("stars") or []]
        yield f.name, r


def is_ffa(row: dict) -> bool:
    """More than two players and no teams (2v2 and other team games have repeated team ids)."""
    teams = row.get("teams")
    return len(row.get("usernames") or []) > 2 and not (teams and len(set(teams)) < len(teams))


# ---------------------------------------------------------------- compact records

def to_record(prep: dict) -> dict:
    """replay_prep.prepare output -> compact record: moves stored sparsely as (tick, player, row, col, dir, split)."""
    a, afk = prep["actions"], prep["afk"]
    t, p = np.nonzero(a[:, :, 0] == 0)
    moves = np.concatenate([t[:, None], p[:, None], a[t, p, 1:]], 1).astype(np.int16)
    ft, fp = np.nonzero(afk)
    afks = np.stack([ft, fp, afk[ft, fp]], 1).astype(np.int16)
    return dict(grid=prep["grid"].astype(np.int16), teams=prep["teams"].astype(np.int8), moves=moves, afks=afks)


def load_game(d, g: int):
    """Game g of a processed .npz -> dense simulator inputs: grid (PAD, PAD), actions (T, NP, 5), afk (T, NP),
    teams (NP,), number of ticks T."""
    mv = d["moves"][d["move_offsets"][g]:d["move_offsets"][g + 1]].astype(np.int32)
    af = d["afks"][d["afk_offsets"][g]:d["afk_offsets"][g + 1]].astype(np.int32)
    t = int(d["n_ticks"][g])
    actions = np.tile(PASS, (t, NP, 1))
    actions[mv[:, 0], mv[:, 1]] = np.concatenate([np.zeros((len(mv), 1), np.int32), mv[:, 2:]], 1)
    afk = np.zeros((t, NP), np.int32)
    afk[af[:, 0], af[:, 1]] = af[:, 2]
    return d["grids"][g].astype(np.int32), actions, afk, d["teams"][g].astype(np.int32), t


def start_state(d, g: int):
    """The initial GameState of game g of a processed .npz (a real map: its mountains, cities and spawns), plus the
    map size (h, w), the number of real players and the usernames."""
    meta = json.loads(str(d["meta"]))[g]
    w, h = meta["map"]
    state = game.create_initial_state(jnp.asarray(d["grids"][g], jnp.int32), teams=jnp.asarray(d["teams"][g], jnp.int32))
    return state, (h, w), int(d["n_players"][g]), meta["usernames"]


def pad_ticks(x: np.ndarray, t_pad: int, fill=None) -> np.ndarray:
    """Pad the leading (tick) axis to t_pad: actions with passes (fill=PASS), everything else with zeros."""
    out = np.zeros((t_pad,) + x.shape[1:], x.dtype)
    if fill is not None:
        out[:] = fill
    out[: x.shape[0]] = x
    return out


def bucket(t: int, size: int = 256) -> int:
    """Round a tick count up so the simulation compiles once per bucket."""
    return -(-t // size) * size


# ---------------------------------------------------------------- simulation

@jax.jit
def simulate(grid: jnp.ndarray, actions: jnp.ndarray, afk: jnp.ndarray, teams: jnp.ndarray):
    """Replay a recorded game. AFK events are applied at the start of their tick, like the site does.

    Returns per tick t (the state *before* that tick's moves):
        states  GameState stacked (T, ...); features.observe turns it into any player's view
        legal   (T, NP) recorded move of each player is executable (passes count as legal)
        winner  (T,) winner after the tick, -1 while running
    and final_eliminated (NP,) after the last tick (the decisive capture is not yet in `states`).
    """
    n = actions.shape[1]
    s0 = game.create_initial_state(grid, teams=teams)

    def tick(s, inp):
        a, ev = inp
        for p in range(n):
            for rep in range(2):
                s = jax.lax.cond(ev[p] > rep, lambda s, p=p: replay_prep.afk_event(s, p), lambda s: s, s)
        si, sj = a[:, 1], a[:, 2]
        legal = (a[:, 0] != 0) | (s.ownership[jnp.arange(n), si, sj] & (s.armies[si, sj] >= 2) & ~s.eliminated)
        s2, info = game.step(s, a, general_trade=True)
        return s2, (s, legal, info.winner)

    final, (states, legal, winner) = jax.lax.scan(tick, s0, (actions, afk))
    return states, legal, winner, final.eliminated


def placements(eliminated: np.ndarray, final_eliminated: np.ndarray, n_players: int) -> np.ndarray:
    """Final placement (1 = best) of each real player from the per-tick elimination flags (T, NP) and the flags
    after the last tick: whoever drops out later places better; players never eliminated share first place.
    (Passing eliminated[:n_ticks] matters: ticks beyond the game's end are padding.)"""
    eliminated = np.concatenate([eliminated, final_eliminated[None]], 0)
    t = eliminated.shape[0]
    out_at = np.where(eliminated.any(0), eliminated.argmax(0), t)[:n_players]   # tick of elimination, t if never
    return 1 + (out_at[None, :] > out_at[:, None]).sum(1)                        # players that lasted longer
